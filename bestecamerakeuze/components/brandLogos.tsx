/** Normaliseert een merknaam ("Škoda", " Audi ", "SEAT") naar een sleutel in BRAND_LOGOS. */
function normaliseer(merk: string): string {
  return merk
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}

/** Geeft het logo-component voor een merk terug, of null als er geen logo voor is
 * (bijvoorbeeld "Alle", of een merk dat nog niet in de set zit). */
export function getBrandLogo(merk: string): LogoComponent | null {
  return BRAND_LOGOS[normaliseer(merk)] ?? null;
}
